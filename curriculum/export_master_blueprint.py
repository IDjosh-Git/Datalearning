"""Export the app's authored four-level pathway to a readable curriculum blueprint."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'assets/data/master-learning-pathway.json').read_text(encoding='utf-8'))
lines=[]
def put(s=''):lines.append(s)
put('# DataLearning — Four-Level Master Curriculum Blueprint')
put('**Curriculum review:** 10 November 2026 · **Audience:** absolute beginners, practising analysts, engineers, and aspiring AI/data-science specialists.')
put('')
put('## 1. Gap analysis summary')
put('')
put('### Strengths in the existing app')
put('- Seven active 10-week courses (Data Analysis, Excel, SQL, Power BI, Tableau, Power Query, Introductory Statistics), each with worked examples, guided steps, weekly questions, and saved completion states. The separate Python and AI course routes are retained for continuity.')
put('- Practical exercises, SQL and spreadsheet practice surfaces, progress tracking and capstone tools already exist. These provide a strong beginner-to-intermediate analytics base.')
put('')
put('### What needed improvement and has been added')
put('- **A clear four-stage progression:** the core 70 weeks were not visibly connected to data engineering, machine learning or expert AI systems. A new 31-module interactive master pathway bridges those gaps.')
put('- **Data engineering:** data contracts, dbt/Snowflake-style transformation practices, orchestration, cloud architecture, ACID lakehouse tables, Spark and Kafka are now explicitly taught at the appropriate progression level.')
put('- **Data science:** Python, pandas, statistical inference, A/B tests, forecasting, supervised ML, temporal validation and production monitoring are mapped into an ascending sequence.')
put('- **Responsible AI:** prompting for data professionals, grounded retrieval, evaluations, permission boundaries and human verification are separate instructional units rather than generic “use AI” suggestions.')
put('- **Reproducibility and safety:** Git, CI, lineage, privacy and security controls are taught before learners encounter production-scale architecture.')
put('- **Applied depth:** every new specialist module contains a substantial concept explanation, concrete worked example with interpretation, realistic case, four steps, a five-minute micro-project, model answer, and mistake to avoid.')
put('')
put('### Existing topics to keep, reposition or de-emphasize')
put('- **Keep** fundamental arithmetic, basic SQL, ordinary spreadsheet references and descriptive statistics. Beginners need them, but link each lesson to a tangible analysis problem instead of presenting abstract facts alone.')
put('- **De-emphasize as primary techniques** legacy LOOKUP/VLOOKUP and manual copy-paste spreadsheet consolidations. Teach for maintenance and historical literacy; prefer structured tables, XLOOKUP when available, Power Query and validated transforms.')
put('- **Avoid** chart decoration without metric design, memorizing isolated DAX/SQL syntax, cloud vendor names without architecture concepts, and purely theoretical mathematics disconnected from business interpretation.')
put('- **Update assessments next:** some existing weekly multiple-choice items use generic distractors. Those remain unchanged in this compatibility-safe release; a later content-quality pass should introduce more diagnostic, scenario-specific feedback and version existing quiz banks.')
put('')
put('### Delivery and status of implementation')
put('- The complete 31-module supplement is displayed within `catalog.html` beneath the original course catalog. Filter by proficiency and specialization; expand each module to read the practical lesson and reveal the model answer.')
put('- The seven existing 10-week courses link to the relevant specialist modules. **No existing course slug, week number, quiz result or Supabase progress record is changed.**')
put('- The specialist material runs as **mobile-friendly reading, offline synthetic calculations and planning challenges**. Cloud warehouses, Spark, Kafka, MLflow and AI APIs are instructional topics; these cloud platforms are **not** emulated or connected by the new content.')
put('- Treat `E08` as an assessed portfolio assignment and `F01–F07` as a zero-experience on-ramp. Estimated durations are only instructional planning estimates, not measured completions.')
put('')
put('## 2. Proficiency-level guide')
put('')
for lv in data['levels']:
    put(f"### Level {lv['id']} — {lv['name']} ({lv['subtitle']})")
    put(f"**Objective:** {lv['description']} **Suggested guided study:** {lv['hours']}, plus independent project time.")
    put('')
put('## 3. Updated master curriculum table')
put('')
put('| Level | Module name | Primary tools | Learning outcome |')
put('|---|---|---|---|')
for m in data['modules']:
    put(f"| {m['level']} · {next(x['name'] for x in data['levels'] if x['id']==m['level'])} | **{m['id']}** {m['title']} | {m['tools']} | {m['outcome']} |")
put('')
put('## 4. Detailed module breakdowns')
put('')
for lv in data['levels']:
  put(f"## Level {lv['id']}: {lv['name']} — {lv['subtitle']}")
  put('')
  for m in (m for m in data['modules'] if m['level']==lv['id']):
    put(f"### {m['id']} · {m['title']}")
    put(f"**Discipline:** {m['track']}  ")
    put(f"**Primary tools:** {m['tools']}  ")
    put(f"**Learning objective:** {m['outcome']}  ")
    put(f"**Prerequisites:** {m['prerequisites']}")
    put('')
    put('**Core topics:** '+ '; '.join(m['topics'])+'.')
    put('')
    put('**Teach the concept:** '+m['lesson'])
    put('')
    put('**Business case study:** '+m['caseStudy'])
    put('')
    put('**Guided practical walkthrough:**')
    for i,step in enumerate(m['steps'],1):put(f'{i}. {step}.')
    put('')
    put('**Worked example:**')
    put('')
    put('```text')
    put(m['workedExample'])
    put('```')
    put('')
    put('**How to interpret the result:** '+m['interpretation'])
    put('')
    put('**Five-minute mobile micro-project:** '+m['microProject'])
    put('')
    put('**Model answer:** '+m['modelAnswer'])
    put('')
    put('**Common mistake:** '+m['commonMistake'])
    put('')
    put('**Next step:** '+m['next'])
    put('')
put('## 5. Suggested teaching and assessment workflow')
put('')
put('1. **Micro-lesson (3–5 min):** describe one concept with a plain-language analogy and an explicit example.')
put('2. **Worked example (3–5 min):** identify input data, operation, output, interpretation and limitations.')
put('3. **Guided practice (5–10 min):** use a six-row synthetic dataset or a read-only query/formula in the app.')
put('4. **Knowledge check (2–3 min):** short diagnostic question, feedback for wrong answers and a revealed worked solution.')
put('5. **Case application (15–45 min):** gradually extend the micro-project into a business decision, a reproducible script or an architecture sketch.')
put('6. **Evidence checkpoint:** source-to-result reconciliation, documented assumptions, limitation statement and rubric-based review before earning a credential.')
put('')
put('### Suggested capstone gates')
put('- **Level 1:** clean and summarize six synthetic orders, explain the metric, show a table and a chart.')
put('- **Level 2:** produce a refreshable business dashboard with SQL joins, checks and a short insight memo.')
put('- **Level 3:** prototype an auditable transformation pipeline or validation-aware ML experiment with CI and tests.')
put('- **Level 4:** architecture plus demonstrable synthetic tests for access, lineage, latency, reliability, a failure drill and human-reviewed AI behavior.')
put('')
put('### Tool and cost safeguards')
put('- Mobile/app exercises should work with miniature synthetic datasets. Where real Spark/Kafka/cloud access is unavailable, clearly label the activity **simulation or design exercise**.')
put('- Optional paid cloud labs should have a published spending cap, teardown steps and free/local alternatives. Do not require credentials or real customer data for an introductory task.')
put('- Practical assessment should measure correctness, interpretation, reproducibility and security—not simply a page visit or attractive output.')
put('')
put('## 6. Modern reference topics (official documentation)')
put('')
put('- Microsoft Learn, Apache Spark in Fabric: https://learn.microsoft.com/en-us/training/modules/use-apache-spark-work-files-lakehouse/')
put('- Microsoft Learn, Fabric Data Engineering overview: https://learn.microsoft.com/en-us/fabric/data-engineering/data-engineering-overview')
put('- dbt Developer Hub, best-practice guides: https://docs.getdbt.com/best-practices')
put('- Google for Developers, production ML monitoring: https://developers.google.com/machine-learning/crash-course/production-ml-systems/monitoring')
put('- Microsoft Learn, Copilot in Fabric Data Engineering: https://learn.microsoft.com/en-us/training/modules/get-started-copilot-fabric-data-engineering')
put('')
put('**Privacy and progress:** this release adds curriculum content and links only; existing Supabase tables, authentication, learner records, week progress, and assessment results are not migrated or reset.')
output=ROOT/'docs/MASTER_FOUR_LEVEL_CURRICULUM_20261110.md'
output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Wrote blueprint:',output, 'length',output.stat().st_size)

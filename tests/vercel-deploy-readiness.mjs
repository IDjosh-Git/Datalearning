/* Deployment contract: Vercel must run verification and retain the existing routing/API topology. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>fs.readFileSync(path.join(ROOT,name),'utf8');
const vercel=JSON.parse(read('vercel.json'));
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.engines.node,'24.x','Pin a known-supported, tested Vercel Node LTS');
assert.equal(read('.nvmrc').trim(),'24','Local Node version must match Vercel engines');
assert.equal(vercel.framework,null,'Keep the existing static-site + Vercel API configuration');
assert.equal(vercel.outputDirectory,'.','Static HTML and assets must deploy from repository root');
assert.equal(vercel.buildCommand,'npm run build','Vercel must execute source verification before deployment');
assert(!/npm run verify:deployment/.test(vercel.buildCommand),'Avoid recursive/heavy nested build scripts');
assert(!Array.isArray(vercel.builds),'Do not use legacy builds config which can drop static assets');
for(const name of ['index.html','auth.html','catalog.html','service-worker.js','api/tutor.js','api/auth/session.js','middleware.js','assets/styles/design-system.css','assets/styles/private-workspace.css'])assert(fs.existsSync(path.join(ROOT,name)),`Missing deployment-critical ${name}`);
const resolveRewrite=source=>vercel.rewrites.some(x=>x.source===source);
for(const route of ['/dashboard','/studio','/practice','/courses/:course'])assert(resolveRewrite(route),`Missing Vercel rewrite ${route}`);
assert(vercel.headers.some(h=>h.source==='/service-worker.js' && h.headers.some(x=>x.key.toLowerCase()==='cache-control'&&x.value.includes('no-store'))),'Service worker must refresh on new deployments');
const mid=read('middleware.js');
assert(mid.includes('@vercel/functions')&&mid.includes('matcher:'),'Admin middleware must be registered');
assert(mid.includes("'/admin.html'")&&mid.includes("'/reviewer.html'"),'Protect private routes');
assert(read('api/auth/session.js').includes("'Set-Cookie'"),'Session endpoint must remain in the deployment');
assert(read('service-worker.js').includes('dalp-public-home-premium-v30'),'Release cache should refresh for returning visitors');
const expected=['TUTOR_PROVIDER','GROQ_API_KEY','GROQ_MODEL','OPENAI_API_KEY'];
assert(expected.every(k=>read('.env.example').includes(k)),'Document the provider setup for deployment');
console.log('PASS Vercel readiness: explicit build verification, Node 24 pin, static root, rewrites, API functions, middleware and cache headers.');

/** Regression: compact subject badges and a single challenge brief across editor modes. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
const page=fs.readFileSync('practice.html','utf8');
const ide=fs.readFileSync('assets/scripts/arena-ide.js','utf8');
const stable=fs.readFileSync('assets/scripts/arena-stability.js','utf8');
const style=fs.readFileSync('assets/styles/practice-arena-premium-final.css','utf8');
const practice=fs.readFileSync('assets/scripts/practice.js','utf8');
assert(page.includes('arena-ide.js?v=arena-unified-20261111-r1'),'Toolbar changes must have a refreshed asset URL');
assert(page.includes('arena-stability.js?v=arena-task-dedup-20261111-r1'),'Duplicate removal must have a refreshed asset URL');
assert(page.includes('practice-arena-premium-final.css?v=20261111-mobile-sql-results-r2'),'Compact styling must have a refreshed asset URL');
assert.equal((practice.match(/class="arena-learning-brief"/g)||[]).length,1,'Retain one challenge brief at top');
assert(!stable.includes('CHALLENGE BRIEF'),'No additional task brief in IDE');
assert(!stable.includes('data-arena-view="task"'),'Mobile tabs must not provide duplicate task panel');
assert(stable.includes('data-arena-view="editor"')&&stable.includes('data-arena-view="output"'),'Keep editor and output navigation');
assert(stable.includes("root.querySelector('.arena-task-panel')?.remove()"),'Remove old task panel from existing DOM');
for(const id of ['ideSqlMode','ideExcelMode','idePythonMode'])assert(ide.includes(`id="${id}"`),`Missing ${id}`);
assert.equal((ide.match(/class="ide-brand-mark"/g)||[]).length,3,'Each tool logo must have a constrained badge');
assert.equal((ide.match(/width="23" height="23"/g)||[]).length,3,'Explicit logo dimensions must prevent intrinsic SVG expansion');
for(const property of ['.ide-brand-mark','.ide-brand-img','object-fit:contain','width:23px!important','max-width:23px!important','@media(max-width:540px)'])assert(style.includes(property),`Missing compact responsive toolbar rule: ${property}`);
console.log('PASS Practice Arena: constrained SQL/Excel toolbar icons, mobile two-panel navigation, one preserved top challenge brief');

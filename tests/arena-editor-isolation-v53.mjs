import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const root=path.resolve(import.meta.dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const html=read('practice.html');
const practice=read('assets/practice.js');
const ide=read('assets/arena-ide.js');
const mobile=read('assets/arena-stability.js');
const css=read('assets/arena-editor-isolation-v53.css');
for(const kind of ['SQL','Excel','Python']) {
  assert.match(html,new RegExp(`data-arena-subject="${kind}"`));
  assert.match(css,new RegExp(`data-active-editor="${kind}"`));
}
assert.match(practice,/dataset\.activeEditor=t\.kind/);
assert.match(practice,/dalp:arena-editor-selected/);
assert.match(ide,/subject!=='SQL'&&subject!=='Excel'/);
assert.match(ide,/\['SQL','Excel'\]\.includes\(area\.dataset\.activeEditor\)/);
assert.match(mobile,/select\('editor',shell\)/);
assert.match(css,/overflow-y:auto!important/);
assert.match(css,/clip-path:none!important/);
assert.match(html,/arena-editor-isolation-v53\.css\?v=20261028\.53/);
assert.match(html,/arena-stability\.js\?v=20261028\.53/);
const context={window:{}};
vm.runInNewContext(read('assets/python-challenges-v42.js'),context,{filename:'python-challenges-v42.js'});
const python=context.window.DALP_PY_CHALLENGES;
assert.equal(python.length,54,'All 54 Python challenges must remain available');
assert.ok(python.every(ch=>ch.kind==='Python'));
console.log('PASS editor isolation v53: SQL / Excel / Python selectors, mobile editor default, readable Python instructions, 54 challenges');

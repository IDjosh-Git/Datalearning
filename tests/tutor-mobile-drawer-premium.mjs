import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const html = readFileSync(new URL('tutor.html',root),'utf8');
const js = readFileSync(new URL('assets/scripts/tutor-workspace.js',root),'utf8');
const css = readFileSync(new URL('assets/styles/tutor-mobile-drawer.css',root),'utf8');
assert.match(html,/class="tutor-drawer-bar"/,'AI Tutor drawer must have a dedicated mobile header');
assert.match(html,/id="tutorCloseSettings"[^>]*type="button"/,'Close button must be reachable');
assert.match(html,/tutor-mobile-drawer\.css\?v=tutor-drawer-20261110-r1/,'Load final scoped CSS with cache revision');
assert.match(js,/drawer\.setAttribute\('aria-modal','true'\)/,'Mobile drawer should identify as modal');
assert.match(js,/drawer\.toggleAttribute\('inert',mobile\.matches&&!active\)/,'Inactive drawer must be inert');
assert.match(js,/closeButton\?\.addEventListener\('click',\(\)=>close\(true\)\)/,'Close action must restore focus');
assert.match(js,/event\.key==='Escape'/,'Escape must close');
assert.match(js,/event\.key!=='Tab'/,'Keyboard tab focus should remain inside drawer');
assert.match(css,/\.tutor-settings-open main\.tutor-main/,'Mobile drawer must render above page header');
assert.match(css,/\.tutor-settings-close:focus-visible/,'Close button must have accessible focus styling');
assert.match(css,/max-width:900px/,'Mobile only rules should not affect desktop Tutor layout');
console.log('PASS Tutor mobile premium drawer close, keyboard focus, stacking, and responsive styling');

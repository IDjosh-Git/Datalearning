/** Full-height tutor workspace contract; live viewport geometry is covered by the browser layout check. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const html=readFileSync(new URL('tutor.html',root),'utf8');
const css=readFileSync(new URL('assets/styles/premium-unified.css',root),'utf8');
assert.match(html,/class="tutor-mobile-back"[^>]+href="index.html"|class="tutor-mobile-back"[^>]+aria-label="Back to Discover"/);
assert.match(html,/id="chatMessages"/);
assert.match(html,/id="tutorToolsToggle"/);
assert.match(html,/id="tutorToolsPanel"/);
assert.match(html,/id="chatForm"/);
assert.match(html,/id="chatQuestion"/);
assert.match(html,/id="sendQuestion"/);
assert.match(html,/interactive-widget=resizes-content/);
const drawerStart=html.indexOf('class="chat-side tutor-sidebar"');
const drawerEnd=html.indexOf('</aside>',drawerStart);
assert(drawerStart>=0 && drawerEnd>drawerStart,'Tutor drawer must exist');
assert(html.slice(drawerStart,drawerEnd).includes('class="tutor-privacy-disclosure"'),'Privacy is now inside the Tools drawer');
assert.match(css,/Tutor immersive mobile viewport/);
assert.match(css,/@media \(max-width:900px\)/);
assert.match(css,/body\[data-responsive-page="tutor"\] > \.dalp-global-header/);
assert.match(css,/\.tutor-chat \.messages > \*\{/);
assert.match(css,/max-height:none!important;overflow-y:auto!important/);
assert.match(css,/100dvh!important/);
console.log('PASS full-height mobile Tutor layout, anchored composer, accessible exit, scrollable messages, and Tools drawer');

import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const pages=[...fs.readdirSync(root).filter(n=>n.endsWith('.html')).map(n=>path.join(root,n)),...fs.readdirSync(path.join(root,'courses')).filter(n=>n.endsWith('.html')).map(n=>path.join(root,'courses',n))];
const privatePages=pages.filter(file=>fs.readFileSync(file,'utf8').includes('data-private-workspace="true"'));
assert.equal(pages.length,40,'One unified loader across all public and private routes');
assert.equal(privatePages.length,8,'Eight protected workspaces');
const extract=(markup)=>markup.slice(markup.indexOf('<div id="dlxPageLoader"'),markup.indexOf('</div><script src=',markup.indexOf('<div id="dlxPageLoader"'))+6);
const shared=extract(fs.readFileSync('index.html','utf8'));
assert(shared.includes('dlx-loader-wordmark')&&shared.includes('dlx-loader-orbit'));
for(const file of pages){
 const html=fs.readFileSync(file,'utf8');
 const prefix=file.includes(`${path.sep}courses${path.sep}`)?'../':'';
 for(const text of [`${prefix}assets/styles/page-loader.css?v=unified-20261110-r2`,`${prefix}assets/scripts/page-loader.js?v=unified-20261110-r2`,"classList.add('dlx-loader-pending')",'id="dlxPageLoader"','Preparing your next insight'])assert.ok(html.includes(text),`${path.relative(root,file)} missing ${text}`);
 assert.equal((html.match(/id="dlxPageLoader"/g)||[]).length,1,`${path.relative(root,file)}: exactly one loader`);
 assert.equal(extract(html),shared,`${path.relative(root,file)}: same actual loader markup`);
 assert(!html.includes('dlpPageLoader')&&!html.includes('dlp-loader-pending')&&!html.includes('dlp-loader-emblem'),`${path.relative(root,file)}: retired loader removed`);
}
const css=fs.readFileSync('assets/styles/page-loader.css','utf8');
const js=fs.readFileSync('assets/scripts/page-loader.js','utf8');
const guard=fs.readFileSync('assets/styles/access-guard.css','utf8');
const auth=fs.readFileSync('assets/scripts/auth-gate.js','utf8');
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(css,/html\.dalp-auth-checking\.dlx-loader-pending body>#dlxPageLoader/);
assert.match(js,/DOMContentLoaded/);
assert.match(js,/dalp:auth-ready/);
assert.match(js,/dalp:auth-gate-state/);
assert.match(js,/MAX_PUBLIC_WAIT=2800/);
assert.match(js,/root\.classList\.contains\('dalp-auth-checking'\)/);
assert.match(guard,/body > \*:not\(#dalp-auth-gate\):not\(#dlxPageLoader\)/);
assert.match(guard,/\.dalp-gate-loading\{display:none!important\}/);
assert.match(auth,/dalp-gate-loading/);
assert.match(auth,/dalp:auth-gate-state/);
assert(!auth.includes('dalp-gate-spin'),'Retired auth spinner removed from runtime');
for(const f of fs.readdirSync('assets/styles').filter(f=>f.endsWith('.css')))assert(!fs.readFileSync(path.join('assets/styles',f),'utf8').includes('dalp-gate-spin'),`Old auth spinner style remains in ${f}`);
console.log(`PASS unified branded loader on ${pages.length} routes, ${privatePages.length} protected routes, secure auth handoff, no obsolete spinner, reduced-motion`);

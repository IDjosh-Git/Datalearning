import assert from 'node:assert/strict';
import fs from 'node:fs';
const base = new URL('../',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,base),'utf8');
const cap=read('assets/scripts/capstone.js'),profile=read('profile.html');
const client=read('assets/scripts/profile-editor.js'),nav=read('assets/scripts/profile-navigation.js');
const sql=read('database/20261108_datalearning_profile_avatars.sql');
const css=read('assets/styles/premium-unified.css');
assert(cap.includes('auth.getSession()'),'Capstone must distinguish logged-out from failed request');
assert(cap.includes('auth.getUser()'),'Capstone must verify an active account');
assert(cap.includes('reviewLoaded'),'Capstone must not enable submissions before history is known');
assert(cap.includes('Retry loading'),'Transient failures must offer a retry');
assert(!cap.includes("We couldn't load your project submissions"),'Legacy misleading message must be removed');
assert(profile.includes('id="profilePhotoTrigger"'),'Photo upload should be keyboard accessible');
for(const id of ['profileDetailsForm','profileAvatarImg','profileEmailForm','profilePasswordForm','profileFullName','profileHeadline','profilePhone','profileLocation','profileGoal','profileBio'])assert(profile.includes('id="'+id+'"'),'Missing editable profile field '+id);
assert(client.includes('dalp_avatar_path') && client.includes('auth.updateUser'),'Avatar path and profile must sync with authenticated owner');
assert(client.includes('profilePhotoTrigger'),'Photo trigger missing');
assert(nav.includes('dalp:profile-updated')&&nav.includes('Signed in')&&nav.includes('Guest'),'Header profile state must be live');
assert(sql.includes("'datalearning-avatars'"));
for(const stmt of ['FOR SELECT TO authenticated','FOR INSERT TO authenticated','FOR UPDATE TO authenticated','FOR DELETE TO authenticated','(select auth.uid())'])assert(sql.includes(stmt),'Avatar RLS missing '+stmt);
assert(css.includes('mobile top navigation polish'));
assert(css.includes('cap-hero.dalp-themed-hero'));
assert(read('assets/scripts/discover-live.js').includes('prefers-reduced-motion: reduce'));
console.log('PASS Capstone + profile release: verified session states, safe avatar upload, role-aware top navigation, responsive redesign and live Discover motion');

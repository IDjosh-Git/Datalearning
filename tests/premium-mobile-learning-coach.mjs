import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=f=>fs.readFileSync(new URL('../'+f,import.meta.url),'utf8');
const footer=read('assets/scripts/public-footer.js');
const coach=read('assets/scripts/learner-companion.js');
const css=read('assets/styles/premium-unified.css');
assert(footer.includes('data-learning-coach-link="true"'),'Footer launches the actual Learning Coach');
assert(coach.includes("[data-learning-coach-link]"),'Coach handles footer interaction');
assert(coach.includes('e.preventDefault();lastOpenTrigger=link;open()'),'Coach launches without changing route');
assert(coach.includes("location.hash==='#learning-coach'"),'Fallback deep link launches the Coach');
assert(css.includes('display:grid!important;place-items:center!important'),'Video must be centered');
assert(css.includes('body[data-course] .dalp-video-panel'),'Centered video panel must be styled');
assert(css.includes('width:100%!important;max-width:520px!important'),'Mobile video remains a floating card');
assert(css.includes('.tutor-toolbar{border-radius:0!important'),'Tutor top must have square edges on mobile');
assert(css.includes('font-family:"Plus Jakarta Sans"'),'Shared premium heading font');
console.log('PASS centred video, Learning Coach footer integration, mobile Tutor and typography');

import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const courses=['introduction','excel','sql','powerbi','python','ai'];
const css=read('assets/styles/premium-unified.css');
const drawer=read('assets/scripts/course-premium-sidebar.js');
for(const slug of courses){
 const page=read(`courses/${slug}.html`);
 assert.equal((page.match(/id="sidebar"/g)||[]).length,1,`${slug}: expected exactly one lesson sidebar`);
 assert.equal((page.match(/id="menuBtn"/g)||[]).length,1,`${slug}: expected a single mobile lessons trigger`);
 assert.equal((page.match(/class="dl-lesson-mobile-bar"/g)||[]).length,1,`${slug}: missing responsive lesson bar`);
 assert.doesNotMatch(page,/data-primary-course-nav|class="dlp97-navigation"|id="dlp97-side"/,`${slug}: retired all-courses sidebar still embedded`);
 assert.match(page,/course-premium-sidebar\.js/,`${slug}: accessible drawer controller missing`);
 assert.match(page,/class="sidebar dl-lesson-rail(?: dl-special-lesson-rail)?"/,`${slug}: lesson rail should use the unified component`);
 assert.match(page,/id="courseLessonIndex"/,`${slug}: lesson outline index missing`);
 assert.match(page,/assets\/scripts\/learning-catalog\.js/,`${slug}: learning progress guide missing`);
 assert.doesNotMatch(page,/course-mobile-drawer\.js|course-layout-theme\.js/,`${slug}: retired drawer controller still loads`);
 assert.match(page,/learning-experience\.js/,`${slug}: preserve practice challenges and accessibility enhancements`);
 const links=(page.match(/href="#(?:week\d+|lesson-\d+|case-study|knowledge-check)"/g)||[]).length;
 assert(links>=9,`${slug}: lesson links missing`);
}
assert.match(css,/Single premium LESSON sidebar/);
assert.match(css,/sitewide subject sidebar intentionally removed|Sitewide subject sidebar intentionally removed/);
assert.match(drawer,/aria-expanded/);
assert.match(drawer,/Escape/);
assert.match(drawer,/inert/);
assert.match(drawer,/dl-lesson-rail-open/);
assert.match(read('assets/scripts/responsive.js'),/!sidebar\.classList\.contains\('dl-lesson-rail'\)/,'Legacy drawer controller must not override new lesson sidebar');
assert.match(css,/\.app:has\(> #sidebar\.dl-lesson-rail\)/,'Course drawer must layer above mobile scrim');
assert.doesNotMatch(read('assets/scripts/learning-experience.js'),/dalp-lesson-next|guideNextLesson/, 'Old next-lesson overlay still present');
assert.doesNotMatch(read('assets/scripts/experience.js'),/experience-study-map/, 'Old study-map overlay still present');
assert.doesNotMatch(read('assets/scripts/learning-catalog.js'),/dlp97-side|dlp97-menu-toggle|holder\.querySelector/, 'Retired course-list sidebar script remains');
for(const file of ['course-mobile-drawer.js','course-layout-theme.js'])assert(!fs.existsSync('assets/scripts/'+file),`Obsolete ${file} still deployed`);
const sw=read('service-worker.js');
assert.match(sw,/dalp-public-premium-responsive-v53/);
assert.doesNotMatch(sw,/const PUBLIC = .*html\|css\|js/);
const headers=JSON.parse(read('vercel.json')).headers;
assert(headers.some(h=>h.source.includes('scripts|styles')&&h.headers.some(x=>x.key==='Cache-Control'&&x.value.includes('no-store'))));
console.log('PASS all six courses use one premium lesson sidebar, no course-list rail, and an accessible mobile lesson drawer');

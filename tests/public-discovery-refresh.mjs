import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const landing=read('public-pages/landing.html');
assert.match(landing,/id="dlWeeklyHeroImage"/);
assert.match(landing,/home-weekly-photo\.js/);
for(const link of ['/start-here','/courses','/career-paths','/free-lesson'])assert(landing.includes(`href="${link}"`),`Homepage must link to ${link}`);
const start=read('public-pages/start-here.html');
assert.match(start,/id="start-route-title"/);
for(const path of ['/courses/introduction','/courses/excel','/courses/sql'])assert(start.includes(`href="${path}"`));
const catalogue=read('course-info/catalog.html');
assert.match(catalogue,/id="dlCourseSearch"/);
assert.match(catalogue,/id="dlCourseGrid"/);
assert.match(catalogue,/input\.addEventListener\('input',update/);
assert.equal((catalogue.match(/class="card"/g)||[]).length,9);
assert.match(read('public-pages/free-lesson.html'),/id="preview-next"/);
assert.match(read('public-pages/career-paths.html'),/id="career-next"/);
assert.match(read('assets/scripts/home-weekly-photo.js'),/\/assets\/images\/capstone-dashboard-preview\.webp/);
console.log('PASS public discovery: weekly hero, four public routes, course filtering, nine cards, onboarding and preview');

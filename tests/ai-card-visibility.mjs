import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=x=>fs.readFileSync(x,'utf8');
const home=read('index.html'), account=read('account.html'), css=read('assets/styles/home.css');
assert.equal((home.match(/data-track="ai"/g)||[]).length,1,'AI course must appear exactly once on homepage');
assert(home.indexOf('data-track="ai"')>home.indexOf('data-track="intro"'),'AI must follow Introduction');
assert(home.indexOf('data-track="ai"')>home.indexOf('data-track="powerbi"'),'AI must be the last course');
assert(home.includes('aria-label="Open AI Integration in Data Analysis course"'),'AI homepage card CTA must be accessible');
assert(home.includes('id="ai-progress"') && home.includes('id="ai-progress-text"'),'AI homepage progress must exist');
assert(home.includes('>6 courses</span>'),'Course count includes Introduction + five specialists');
assert(css.includes('.lp-home .lp-course[data-track="ai"]') && css.includes('grid-column:auto'),'AI must have a standard one-column footprint');
assert(!css.includes('grid-column:span 2'),'AI must not span multiple columns');
assert(css.includes('.lp-course-cta::after'),'AI homepage card must be fully clickable');
assert(account.includes('class="card ai-account-course-card" href="courses/ai.html"'),'My Learning must contain dedicated clickable AI card');
assert(account.includes('id="aiText"') && account.includes('id="aiBar"'),'My Learning must display AI cloud progress');
assert(account.includes('successful===6') && account.includes('ai:10'),'My Learning must sync six tracks');
assert(account.includes('AI Integration Course ↗'),'My Learning must offer direct AI continuation');
assert(fs.existsSync('courses/ai.html'),'AI course destination must exist');
console.log('PASS AI course last position, equal-size card, clickable links and six-track progress');

import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=x=>fs.readFileSync(x,'utf8');
const home=read('index.html'), account=read('account.html'), css=read('assets/styles/home.css');
assert.equal((home.match(/data-track="ai"/g)||[]).length,0,'No repeated AI course card on Discover');
assert(home.includes('href="courses/ai.html"'),'AI remains accessible from main Courses navigation');
assert.equal((read('catalog.html').match(/data-course="ai"/g)||[]).length,1,'AI has exactly one catalogue entry');
assert(read('catalog.html').includes('aria-label="Course catalog"'),'Course catalogue is accessible');
assert(css.includes('.lp-home .lp-course[data-track="ai"]'),'Course theming is still available for legacy content');
assert(account.includes('class="card progress-card" data-track="ai"') && account.includes('href="courses/ai.html">AI Integration Course ↗</a>'),'My Learning must have AI progress plus a plain course link');
assert(account.includes('id="aiText"') && account.includes('id="aiBar"'),'My Learning must display AI cloud progress');
assert(account.includes('successful===6') && account.includes('ai:10'),'My Learning must sync six tracks');
assert(account.includes('AI Integration Course ↗'),'My Learning must offer direct AI continuation');
assert(fs.existsSync('courses/ai.html'),'AI course destination must exist');
console.log('PASS AI remains unique in catalogue, accessible from navigation and tracked in My Learning');

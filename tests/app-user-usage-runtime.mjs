import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const code = fs.readFileSync('assets/scripts/supabase-client.js','utf8');
let identity=null,calls=[];const cache=new Map();
const storage={getItem:k=>cache.get(k)||null,setItem:(k,v)=>cache.set(k,v)};
const client={auth:{async getUser(){return {data:{user:identity}}}},async rpc(name,args){calls.push({name,args,id:identity?.id});return {data:true,error:null}}};
const win={ZAH_SUPABASE:{url:'https://example.supabase.co',publishableKey:'public-key'},supabase:{createClient(){return client}}};
const sandbox={window:win,document:{readyState:'complete'},sessionStorage:storage,console,Date,Promise};
vm.runInNewContext(code,sandbox);
const tick=()=>new Promise(r=>setTimeout(r,0));
await tick();
assert.equal(calls.length,0,'Logged-out visitor must not become an app user');
identity={id:'guest',is_anonymous:true};
assert.equal(await win.DALP_APP_USAGE.record('use'),false);
assert.equal(calls.length,0,'Anonymous Auth visitor must not become a learner');
identity={id:'learner-1',is_anonymous:false};
assert.equal(await win.DALP_APP_USAGE.record('use'),true);
assert.equal(await win.DALP_APP_USAGE.record('use'),true);
assert.equal(calls.length,1,'Repeat visit should be throttled for the same learner');
identity={id:'learner-2',is_anonymous:false};
assert.equal(await win.DALP_APP_USAGE.record('use'),true);
assert.equal(calls.length,2,'Changing account must not reuse previous account throttle');
assert.equal(await win.DALP_APP_USAGE.record('sign_in'),true);
assert.equal(calls.at(-1).args.p_event,'sign_in');
assert.equal(calls.length,3,'Verified in-app sign-in should be recorded');
console.log('PASS DataLearning app-usage runtime: guest excluded, unique authenticated sessions, account switch, sign-in');

/** Consolidated admin console: no duplicate progress destination, role-safe identity,
 * premium responsive record details and engaged admin participation. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=f=>readFileSync(f,'utf8');
const page=read('admin.html'),js=read('assets/scripts/admin-dashboard.js');
const nav=read('assets/scripts/private-navigation.js'),css=read('assets/styles/admin-unified-premium.css');
const baseCss=read('assets/styles/private-experience-v3.css');
const review=read('reviewer.html');
assert.match(nav,/\['Learners & Progress','admin\.html#admin-learners','learners'\]/);
assert.equal((nav.match(/\['Learners & Progress','admin\.html#admin-learners','learners'\]/g)||[]).length,1);
assert.doesNotMatch(nav,/\['Progress reports','progress\.html'/);
assert.doesNotMatch(page,/href="progress\.html"/);
assert.doesNotMatch(read('assets/scripts/premium-search.js'),/\['progress\.html'/);
assert.match(page,/ac-admin-actions-unified/);
assert.equal((page.match(/class="ac-action-card"/g)||[]).length,2);
for (const id of ['adminRole','adminRosterTotal','adminRosterAdmins','adminRosterLearners','adminRosterEngaged','adminLearnerRows','adminDetailContent','adminLearnerDetail']) assert(page.includes('id="'+id+'"'),id);
assert.match(js,/roleMatch&&match&&st&&co&&inPeriod/,'Role filter is enforced');
assert.match(js,/class="ac-account-role/,'Role badge visible');
assert.match(js,/View details/,'Detail action visible');
assert.match(js,/className='dalp-admin-track ac-detail-course'/,'Detailed path accordions');
assert.match(js,/Array\.from\(\{length:total\}/,'Week-by-week results');
assert.match(js,/memberIds\.has\(r\.user_id\)/,'Only verified directory accounts contribute');
assert.match(js,/profiles\.filter\(p=>profileStats\(p\)\.active\)/,'Active learner metric counts studying administrators');
assert.match(js,/profiles\.filter\(p=>profileStats\(p\)\.paths>0\)/,'Engaged learning includes administrators');
assert.doesNotMatch(js,/owners\.delete\(window\.DALP_AUTH_USER/,'Admin learning must not be deleted from course owners');
assert.doesNotMatch(js,/r\.user_id!==administratorId/,'Admin learning must not be excluded from insights');
assert.match(nav,/className='ac-side-identity'/,'Sidebar identity visible');
assert.match(nav,/accountBadge\.textContent=admin\?'Administrator account'/,'Role is based on verified admin access');
assert.match(nav,/accountEmail\.textContent=account\?\.email/,'Uses current auth account email');
assert.match(css,/box-sizing:border-box!important;inset:0 0 0 auto/,'Mobile detail panel must not spill left');
assert.match(css,/ac-roster-summary/,'Compact metrics cards');
assert.match(css,/ac-detail-course-list/,'Premium progress details');
assert.doesNotMatch(baseCss,/\[data-admin-view="learners"\] \.ac-roster>\.ac-section-header\{padding:clamp\(24px/,'Legacy dark page-wide roster underlay removed');
assert(page.includes('admin-unified-premium.css')&&review.includes('admin-unified-premium.css'),'Current admin and review pages use the unified premium styling');
console.log('PASS single Learners & Progress destination, role/email footer, admin study counted, deep course detail, responsive no-underlay styles');

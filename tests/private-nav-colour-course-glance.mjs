import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const nav = read('assets/styles/private-workspace.css');
const guide = read('assets/styles/course-shared-responsiveness.css');
const navScript = read('assets/scripts/private-navigation.js');
const ai = read('courses/ai.html');
assert.match(nav, /--ac-deep:\s*#152841;/, 'Private sidebar must be deep navy, not white');
assert.match(nav, /--ac-nav-text:\s*#f2f6ff;/, 'Private navigation text must be high contrast');
assert.match(nav, /\.ac-sidebar\{[^}]*background:var\(--ac-deep\)!important/, 'Private navigation colour must be applied to sidebar');
assert.match(nav, /\.ac-side-link:is\([^)]*\)\{[^}]*border-left-color:var\(--ac-nav-accent\)/, 'Active item must use clear accent');
assert.match(nav, /\.ac-drawer-close\{color:#fff/, 'Mobile close control must remain readable');
assert.match(navScript, /const adminNav=/, 'Administrator navigation must remain role-aware');
assert.match(navScript, /const learnerNav=/, 'Learner navigation must remain available');
assert.match(navScript, /root\.classList\.add\('ac-menu-open'\)/, 'Mobile drawer must remain functional');
assert.match(ai, /course-shared-responsiveness\.css/, 'AI Course must load maintained course styles');
assert.match(guide, /One aligned, readable course-at-a-glance panel/, 'Course summary must use shared aligned layout');
assert.match(guide, /\.dalp-quick-guide-intro\s*\{\s*display:\s*grid !important/, 'Summary title and count should use a grid');
assert.match(guide, /@media\(max-width:900px\)/, 'Responsive summary stacking required');
console.log('PASS navy private navigation, clear active state, role-safe links, aligned responsive course summary');
